// Intelligent Offline / Resilient Fallback Engine for Arogyakunj Wellness
// Provides instant, warm, authentic Marathi wellness guidance even when cloud server is unreachable.

export interface OfflineResponse {
  content: string;
  isReminderHandled?: boolean;
}

export function getOfflineWellnessResponse(query: string, reminderDetected?: { title: string; time: string }): OfflineResponse {
  const q = query.toLowerCase().trim();

  // 1. Reminders
  if (reminderDetected) {
    return {
      content: `नक्कीच! 🙏 **${reminderDetected.title}** चा रिमाइंडर **${reminderDetected.time}** वाजता सेट करण्यात आला आहे! ⏰✨\n\n💧 आरोग्य टीप: दिवसभरात किमान ३ ते ४ लिटर पाणी पिणे आणि वेळेवर शेक घेणे आपल्या आरोग्यासाठी खूप फायदेशीर आहे. मस्त ताजेतवाने राहा! 🌿💚`,
      isReminderHandled: true
    };
  }

  // 2. Shake / Formula 1 queries
  if (q.includes('शेक') || q.includes('shake') || q.includes('formula 1') || q.includes('फॉर्म्युला')) {
    return {
      content: `🥤 **हर्बल लाइफ फॉर्म्युला १ न्यूट्रिशनल शेक कसा बनवायचा?** 🌿✨\n\n` +
        `**साहित्य:**\n` +
        `• २५० ते ३०० मिली कोमट किंवा थंड पाणी / स्किम्ड मिल्क (गायचे पातळ दूध)\n` +
        `• ३ चमचे (Scoops) फॉर्म्युला १ शेक मिक्स (तुमचा आवडता फ्लेवर: मँगो, चॉकलेट, व्हॅनिला)\n` +
        `• १ ते २ चमचे पर्सनलाइज्ड प्रोटीन पावडर (PPP)\n\n` +
        `**कृती:**\n` +
        `१. मिक्सर / शेकर जारमध्ये आधी पाणी किंवा दूध टाका.\n` +
        `२. त्यात ३ चमचे शेक मिक्स आणि प्रोटीन पावडर घाला.\n` +
        `३. २० ते ३० सेकंद छान ब्लेंड करा.\n` +
        `४. तुमचा दाट, चवदार आणि पौष्टिक शेक तयार आहे! 💪\n\n` +
        `💡 *टीप: शेकमध्ये भरपूर जीवनसत्त्वे, खनिजे आणि प्रथिने असतात. सकाळच्या नाश्त्याच्या ऐवजी हा शेक घेणे वजन नियंत्रणासाठी अत्यंत उत्तम आहे!* 🌿`
    };
  }

  // 3. Afresh Energy Drink
  if (q.includes('अफ्रेश') || q.includes('afresh') || q.includes('एनर्जी') || q.includes('चहा') || q.includes('tea')) {
    return {
      content: `🍵 **अफ्रेश एनर्जी ड्रिंक (Afresh Energy Drink) फायदे आणि पद्धत** ⚡🌿\n\n` +
        `• **कसा बनवायचा:** १ कप (१५० ते २०० मिली) गरम किंवा थंड पाण्यात १ ग्रॅम (१ चमचा) अफ्रेश मिसळा. साखर घालू नका.\n` +
        `• **मुख्य फायदे:**\n` +
        `  ⚡ शरीरातील सुस्ती आणि थकवा लगेच दूर करतो.\n` +
        `  🔥 चयापचय (Metabolism) वाढवून चरबी कमी करण्यास मदत करतो.\n` +
        `  🧠 मानसिक सतर्कता आणि ताजेतवाने वाटते.\n` +
        `  🌱 साध्या चहा/कॉफीला उत्तम आणि आरोग्यदायी पर्याय आहे!\n\n` +
        `दिवसातून २ ते ३ वेळा तुम्ही अफ्रेश आनंदाने पिऊ शकता! 🍵✨`
    };
  }

  // 4. Water / Hydration
  if (q.includes('पाणी') || q.includes('water') || q.includes('हायड्रेशन') || q.includes('hydration')) {
    return {
      content: `💧 **दररोज किती पाणी प्यावे? - आरोग्यकुंज वेलनेस सल्ला** 🌿\n\n` +
        `निरोगी शरीरासाठी वजनानुसार पाण्याचे प्रमाण:\n` +
        `• **दर २० किलो वजनासाठी १ लिटर पाणी** लागते.\n` +
        `  उदा. तुमचे वजन ६० किलो असल्यास दररोज किमान **३ लिटर पाणी** प्यावे!\n\n` +
        `**महत्त्वाच्या टिप्स:**\n` +
        `🌅 सकाळी उठल्यावर लगेच १-२ ग्लास कोमट पाणी प्या.\n` +
        `🥗 जेवताना किंवा जेवणानंतर लगेच जास्त पाणी पिणे टाळा (जेवणानंतर ३०-४५ मिनिटांनी प्या).\n` +
        `⚡ घोट घोट पाणी बसून पिण्याची सवय ठेवा.\n\n` +
        `तुम्हाला पाणी पिण्याचा रिमाइंडर लावायचा असल्यास "मला १ तासाने पाणी पिण्याची आठवण कर" असे सांगा! ⏰💧`
    };
  }

  // 5. Weight Loss / Diet
  if (q.includes('वजन') || q.includes('weight') || q.includes('loss') || q.includes('डायट') || q.includes('diet') || q.includes('कमी')) {
    return {
      content: `🎯 **वजन कमी करण्यासाठी सोपे आणि प्रभावी ५ नियम:** 🌿💪\n\n` +
        `१. **सकाळचा नाश्ता:** पौष्टिक फॉर्म्युला १ शेक + प्रोटीन घ्या. तळलेले आणि जड पदार्थ टाळा.\n` +
        `२. **भरपूर पाणी:** दिवसातून ३ ते ४ लिटर पाणी पिण्याचे उद्दिष्ट ठेवा.\n` +
        `३. **दुपारचे जेवण:** ५०% ताटात ताजी सॅलड, हिरव्या भाज्या आणि डाळ ठेवा.\n` +
        `४. **साखर आणि मैदा बंद:** गोड पदार्थ, बिस्किटे, बेकरी आयटम पूर्णपणे टाळा.\n` +
        `५. **संध्याकाळी अफ्रेश:** भूक लागल्यास मखाणा किंवा फळ घ्या आणि रात्री हलके जेवण ठेवा.\n\n` +
        `आपण सातत्य (consistency) ठेवल्यास महिन्याला ३ ते ५ किलो वजन सुरक्षितपणे कमी होऊ शकते! 🏆✨`
    };
  }

  // 6. Generic friendly Marathi Wellness greeting / answer
  return {
    content: `नमस्कार! 🙏 **आरोग्यकुंज वेलनेस** मध्ये आपले मनापासून स्वागत आहे! 🌿✨\n\n` +
      `मी आपली वेलनेस कोच आहे. मी आपल्याला खालील गोष्टींमध्ये मदत करू शकते:\n` +
      `• 🥤 **हर्बल लाइफ शेक आणि अफ्रेश रेसिपी**\n` +
      `• 🎯 **वजन कमी / वाढवण्याचा वैयक्तिक डाएट चार्ट**\n` +
      `• 💧 **पाणी आणि जेवणाचे व्हॉईस रिमाइंडर्स**\n` +
      `• 🏃‍♀️ **दैनिक फिटनेस आणि निरोगी जीवनशैली**\n\n` +
      `सांगा, आज तुमची आरोग्य दिनचर्या कशी सुरू आहे? काहीही विचारा! 💚`
  };
}
